"""``--init``: writing a first configuration for a LaTeX project.

The project is analysed (see discover.py), and three files are written next to the main tex file:
* html_config.json: the configuration, with the included files, the TikZ macros, etc.;
* svgbase.tex: the template for the svgs, which uses the preamble of the document, so that its macros and styles
  are available in the diagrams;
* tikz2html.cfg: a tex4ht configuration to start from.
"""

import json
import os

from .discover import analyse_project
from .errors import Tikz2HtmlError

SVG_TEMPLATE = r"""%% The template in which tikz2html compiles every diagram to an svg. Generated by tikz2html --init.
%% tikz2html replaces the placeholders MAIN-FILE and CONTENT-HERE (written with underscores instead of dashes)
%% by the path of the .aux file of the html run and by the diagram.
%% It is compiled with latex (dvi mode) in the folder of the main file, so \tikzfig finds ./figures.
%% If a diagram fails to compile, the cause is often a package in the copied preamble below that doesn't
%% work in dvi mode, or that is not needed for the diagrams: remove such packages here.
DOCUMENTCLASS

% References show the numbers of the html (read from the .aux file written by tex4ht)
\usepackage{xr}
\externaldocument{MAIN_FILE}

%%%%%%%%%% The preamble of MAINNAME.tex %%%%%%%%%%
PREAMBLE
%%%%%%%%%% End of the preamble of MAINNAME.tex %%%%%%%%%%

% Crop every diagram to its contents
\usepackage[active,tightpage]{preview}

% Mark references with raw dvisvgm specials; tikz2html turns these into links to the right html page.
% This is done at the very end of \begin{document} (the begindocument/end hook), because packages like hyperref
% redefine \ref and \eqref at the start of the document.
\makeatletter
\def\tikzhtml@markrefs{%
  \@ifundefined{eqref}{}{\let\tikzhtml@eqref\eqref
    \renewcommand{\eqref}[1]{\special{dvisvgm:raw <eqref>##1}\tikzhtml@eqref{##1}\special{dvisvgm:raw </eqref>}}}%
  \let\tikzhtml@ref\ref
  \renewcommand{\ref}[1]{\special{dvisvgm:raw <ref>##1}\tikzhtml@ref{##1}\special{dvisvgm:raw </ref>}}%
  \@ifundefined{hyperref}{}{\let\tikzhtml@hyperref\hyperref
    \renewcommand{\hyperref}[2][]{\special{dvisvgm:raw <hyperref>##1}\tikzhtml@hyperref[##1]{##2}%
      \special{dvisvgm:raw </hyperref>}}}}
\@ifundefined{AddToHook}{\AtBeginDocument{\tikzhtml@markrefs}}{\AddToHook{begindocument/end}{\tikzhtml@markrefs}}
\makeatother

\begin{document}
CONTENT_HERE
\end{document}
"""

TEX4HT_CONFIG = r"""% tex4ht configuration, generated by tikz2html --init. tikz2html adds the definitions it needs (and the css and
% javascript from html_config.json) to a copy of this file, just before \begin{document}.
% See https://www.kodymirus.cz/tex4ht-doc/ for what can be configured here.
\Preamble{xhtml}
CROSSLINKS
\begin{document}
\EndPreamble
"""

CROSSLINKS = r"""% Links to the previous and next chapter and to the contents, at the top and bottom of every page
\Configure{crosslinks}{\HCode{&nbsp;&nbsp;}}{\HCode{&nbsp;&nbsp;}}{Next}{Previous}{prev-tail}{To the top}{tail}{Contents}
\Configure{crosslinks*}{prev}{up}{next}{}
"""

CONFIG_FILE = "html_config.json"
TEMPLATE_FILE = "svgbase.tex"
TEX4HT_FILE = "tikz2html.cfg"


def svg_template(project) -> str:
    preamble = project.preamble
    lines = preamble.split("\n")
    doc_class = next((line for line in lines if "\\documentclass" in line), "\\documentclass{article}")
    preamble = "\n".join(line for line in lines if "\\documentclass" not in line).strip("\n")
    return (SVG_TEMPLATE.replace("DOCUMENTCLASS", doc_class.strip())
            .replace("MAINNAME", project.main_name).replace("PREAMBLE", preamble))


def make_config(project) -> dict:
    tikz_macros = {"tikz": "ot"}  # \tikz[options]{...} and \tikz \draw ...;
    if project.uses_tikzit:
        tikz_macros.update({"tikzfig": "m", "ctikzfig": "m"})
    tikz_macros.update(project.tikz_macros)
    figure_folder = "figures" if os.path.isdir(os.path.join(project.root, "figures")) else "."
    dependencies = [f for f in project.local_packages if f.endswith(".sty")] + project.other_inputs
    config = {
        "_comment": "Generated by tikz2html --init. Check the values below, in particular other_tex_files and "
                    "tikz_macros; see the README of tikz2html for all the options.",
        "main_name": project.main_name,
        "_comment_files": "The tex files of the document, without .tex (found by following \\input, \\include, "
                          "\\subfile and \\import). Add new files here.",
        "other_tex_files": project.tex_files,
        "html_folder": "html",
        "figure_folder": figure_folder,
        "_comment_macros": "Macros that draw TikZ pictures, with their arguments: m = mandatory, o = optional "
                           "[...], s = star, \"\" = no arguments. Every equation that uses one becomes an svg.",
        "tikz_macros": tikz_macros,
        "tikz_environments": ["tikzpicture"] + project.tikz_environments,
        "skip_environments": ["comment"] + project.excluded_environments,
        "svg_basefile": TEMPLATE_FILE,
        "svg_dependencies": dependencies,
        "svg_scale": 1.3,
        "make4ht_config": TEX4HT_FILE,
        "make4ht_options": "mathml,mathjax,next,2" if project.is_book else "mathml,mathjax",
        "bibtex": ("biber" if project.uses_biblatex else "bibtex") if project.bibliographies else "",
        "additional_css": [],
        "extra_js": [],
        "files_to_copy": project.local_packages + project.other_inputs + project.bibliographies + project.images,
    }
    if not project.is_book:
        config["_comment_options"] = ("A single html page. For one page per section use \"mathml,mathjax,next,3\" "
                                      "(sections are level 3 in tex4ht's numbering).")
    return config


def init_project(main_file, config_name=CONFIG_FILE, overwrite=False, log=print):
    """Writes html_config.json, svgbase.tex and tikz2html.cfg for the project with the given main file.
    Returns the path of the configuration."""
    if not main_file.endswith(".tex"):
        main_file += ".tex"
    if not os.path.isfile(main_file):
        raise Tikz2HtmlError(f"The main file {main_file} does not exist. Give the tex file that you compile (the one "
                             f"with \\documentclass), e.g. tikz2html --init main.tex")
    project = analyse_project(main_file)
    if not project.document_class:
        raise Tikz2HtmlError(f"{main_file} has no \\documentclass; give the main tex file of the document")
    targets = {os.path.join(project.root, os.path.basename(config_name)): None,
               os.path.join(project.root, TEMPLATE_FILE): svg_template(project),
               os.path.join(project.root, TEX4HT_FILE): TEX4HT_CONFIG.replace(
                   "CROSSLINKS", CROSSLINKS if project.is_book else "")}
    existing = [p for p in targets if os.path.exists(p)]
    if existing and not overwrite:
        raise Tikz2HtmlError("These files exist already: " + ", ".join(existing) + ". Use --overwrite to replace "
                             "them, or move them away first.")
    config_path = next(iter(targets))
    targets[config_path] = json.dumps(make_config(project), indent=2) + "\n"
    for path, text in targets.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    report(project, targets, log)
    return config_path


def report(project, written, log):
    log(f"Analysed {project.main_name}.tex ({project.document_class} class):")
    log(f"  included tex files: {', '.join(project.tex_files) or '(none)'}")
    if project.other_inputs:
        log(f"  other included files: {', '.join(project.other_inputs)}")
    macros = ", ".join(f"\\{name}" + (f" [{spec}]" if spec else "") for name, spec in project.tikz_macros.items())
    log(f"  macros that draw TikZ: {macros or '(none found)'}" + (" (plus \\tikzfig, \\ctikzfig from tikzit)"
                                                                   if project.uses_tikzit else ""))
    if project.tikz_environments:
        log(f"  environments that draw TikZ: {', '.join(project.tikz_environments)}")
    if project.excluded_environments:
        log(f"  environments that are left out: {', '.join(project.excluded_environments)}")
    for name, where in project.missing:
        log(f"  Warning: '{name}' (included in {where}) was not found; if it contains TikZ, add it to other_tex_files")
    if project.uses_fontspec:
        log("  Warning: the document uses fontspec/unicode-math, which needs xelatex or lualatex. The svgs are "
            "compiled with latex: remove fontspec from svgbase.tex, or see 'Future work' in the README.")
    if project.uses_biblatex:
        log("  Note: the document uses biblatex, so the bibliography is processed with biber.")
    log("Written: " + ", ".join(os.path.basename(p) for p in written))
    log("Next steps:")
    log("  1. Check html_config.json; in particular tikz_macros: macros that you want to render as html instead "
        "(e.g. by redefining them for tex4ht) should be removed from it.")
    log("  2. Run tikz2html --list to see which parts of the document will become svgs.")
    log("  3. Run tikz2html (in this folder, or with --config) to convert the document.")
