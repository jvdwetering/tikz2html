PX_PER_PT = 4 / 3  # dvisvgm gives sizes in pt, which browsers take as css pt


def size_values(info: dict, scale: float) -> dict:
    """The template fields for the size of an svg, scaled by `scale`: {width} and {height} in px, {size} as html
    attributes, {ratio} for the css aspect-ratio and {valign} for the css vertical-align of inline images.
    The size is given explicitly (instead of scaling with a css transform), so that diagrams don't overlap the
    text around them, and so that the space for them is reserved before they are loaded."""
    if "width" not in info:
        return dict(width="", height="", size="", ratio="auto", valign="middle")
    w = info["width"] * PX_PER_PT * scale
    h = info["height"] * PX_PER_PT * scale
    return dict(width=f"{w:.2f}", height=f"{h:.2f}", size=f' width="{w:.2f}" height="{h:.2f}"',
                ratio=f"{w:.2f} / {h:.2f}", valign=f"{-info['depth'] * PX_PER_PT * scale:.2f}px")


class Fragments:
    """The html fragments used by the placeholders, by key.

    The placeholders in the tex given to make4ht only refer to a key, e.g. \\TikzSvgHtml{inline:ket0}; the html
    itself is defined in a separate file that is loaded by the tex4ht configuration. That way the document only
    contains safe characters, which matters when a placeholder ends up in a moving argument: a figure in a
    \\caption or \\section is also written to the .lof/.toc files, where escaped html characters (like %) would
    break the run."""

    def __init__(self, config: Config):
        self.html = {}
        templates = config.templates
        for star, name in (("", "number"), ("*", "number_tag_star")):
            before, after = split_template(templates[name], "number")
            self.add(f"number{star}:before", before)
            self.add(f"number{star}:after", after)
        self.add("empty", "")

    def add(self, key: str, html: str) -> str:
        self.html[key] = html
        return key

    def definitions(self) -> str:
        """The contents of the file that defines the fragments for tex4ht."""
        lines = ["% Generated by tikz2html: the html of the placeholders of the TikZ diagrams"]
        lines += [f"\\TikzSvgDefine{{{key}}}{{{hcode_escape(html)}}}" for key, html in sorted(self.html.items())]
        return "\n".join(lines) + "\n"


def fragments_file_name(config: Config) -> str:
    return config.main_name + "-tikz2html-html.tex"


def placeholder(block: Block, config: Config, svg_info: dict, fragments: Fragments) -> str:
    """The LaTeX code replacing a block in the tex that is given to make4ht. The html it refers to is added to
    fragments. svg_info maps a block id to a dict with information about the svg (see svg_build.svg_info)."""
    templates = config.templates
    src = f"{config.svg_subfolder}/{block.id}.svg"
    info = svg_info.get(block.id, {})
    values = dict(src=src, name=block.id)
    obj = fill_template(templates["object"], **values, **size_values(info, config.svg_scale))
    labels = "".join(f"\\label{{{label}}}" for label in block.anchor_labels)

    if block.kind == "inline":
        # An <img> is not interactive, so an inline svg with links is embedded with <object> instead
        template = templates["inline_linked" if info.get("linked") else "inline"]
        key = fragments.add(f"inline:{block.id}",
                            fill_template(template, **values, **size_values(info, config.inline_svg_scale)))
        return f"\\TikzSvgHtml{{{key}}}{labels}"

    if block.kind == "block":
        key = fragments.add(f"block:{block.id}", fill_template(templates["block"], object=obj, **values))
        if block.env == "center" or block.env in config.standalone_kinds:
            return f"\\begin{{center}}\\TikzSvgHtml{{{key}}}{labels}\\end{{center}}"
        return f"\\TikzSvgDisplay{{{key}}}{{{labels}}}{{empty}}"

    # display
    if not block.numbers:
        key = fragments.add(f"display:{block.id}",
                            fill_template(templates["display_unnumbered"], object=obj, **values))
        return f"\\TikzSvgDisplay{{{key}}}{{{labels}}}{{empty}}"
    before, after = split_template(fill_template(templates["display"], object=obj, **values), "numbers")
    key_before = fragments.add(f"display:{block.id}:before", before)
    key_after = fragments.add(f"display:{block.id}:after", after)
    numbers = []
    for n in block.numbers:
        if n.tag is not None:
            numbers.append(f"\\TikzSvgTag{'Star' if n.tag_star else ''}{{{n.tag}}}{{{n.label or ''}}}")
        else:
            numbers.append(f"\\TikzSvgEq{{{n.label or ''}}}")
    return f"\\TikzSvgDisplay{{{key_before}}}{{{''.join(numbers)}{labels}}}{{{key_after}}}"


def replace_blocks(text: str, blocks, skipped, config: Config, svg_info: dict, fragments: Fragments) -> str:
    """Returns text with all blocks replaced by placeholders and the skipped spans removed."""
    edits = [(b.start, b.end, placeholder(b, config, svg_info, fragments)) for b in blocks]
    edits += [(s, e, "") for s, e in skipped]
    edits.sort()
    out, pos = [], 0
    for s, e, new in edits:
        if s < pos:
            raise ValueError(f"Overlapping blocks at position {s}")
        out.append(text[pos:s])
        out.append(new)
        pos = e
    out.append(text[pos:])
    return "".join(out)


def restrict_subfiles(text: str, keep, all_files):
    """Comments out \\subfile/\\include/\\input of the source files that are not in keep."""
    drop = [f for f in all_files if f not in keep]
    if not drop:
        return text
    pattern = re.compile(r"^([^%\n]*?)(\\(?:subfile|include|input)\s*\{(?:" +
                         "|".join(re.escape(f) for f in drop) + r")(?:\.tex)?\})", re.M)
    return pattern.sub(lambda m: m.group(1) + "% (skipped by tikz2html) " + m.group(2), text)


