# Characters that need to be escaped to appear literally inside \HCode{..}
_HCODE_ESCAPES = {
    "\\": r"\string\\",
    # The space ends the control word and is skipped by TeX (a {} would end up in the html)
    "{": "\\TikzSvgLbrace ",
    "}": "\\TikzSvgRbrace ",
    "#": r"\#",
    "%": "\\TikzSvgPercent ",
    "&": r"\string&",
    "~": r"\string~",
    "_": r"\string_",
    "^": r"\string^",
    "$": r"\string$",
}


def hcode_escape(html: str) -> str:
    """Escapes a string of html so that it can be passed to \\HCode."""
    return "".join(_HCODE_ESCAPES.get(c, c) for c in html).replace("\n", " ")


def fill_template(template: str, **values) -> str:
    """Replaces {key} by the given values; other braces are left alone (unlike str.format)."""
    return re.sub(r"\{(\w+)\}", lambda m: str(values[m.group(1)]) if m.group(1) in values else m.group(0), template)


def split_template(template: str, key: str):
    """Splits a template at {key} into (before, after)."""
    marker = "{" + key + "}"
    if marker in template:
        before, after = template.split(marker, 1)
        return before, after
    return template, ""


