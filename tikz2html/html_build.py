TEX4HT_DEFINITIONS = r"""
%%%%%%%%%% Added by tikz2html: placeholders for the TikZ diagrams, converted to svg images %%%%%%%%%%
\makeatletter
% Characters that can't appear literally in the html fragments
\edef\TikzSvgPercent{\@percentchar}
\begingroup\catcode`\<=1 \catcode`\>=2 \catcode`\{=12 \catcode`\}=12
\gdef\TikzSvgLbrace<{>\gdef\TikzSvgRbrace<}>\endgroup
% The html fragments are defined by key (in the file FRAGMENTS_FILE), and written out with \tikzsvg@html{key}
\newcommand\TikzSvgDefine[2]{\expandafter\def\csname tikzsvg@#1\endcsname{#2}}
\newcommand\tikzsvg@html[1]{\ifcsname tikzsvg@#1\endcsname\HCode{\csname tikzsvg@#1\endcsname}\else
  \PackageWarning{tikz2html}{Unknown html fragment #1}\fi}
% Inline html (robust, so it can be used in captions and section titles)
\DeclareRobustCommand\TikzSvgHtml[1]{\tikzsvg@html{#1}}
% Display: #1 key of the html before the numbers, #2 the numbers (\TikzSvgEq, \TikzSvgTag) and labels,
% #3 key of the html after
\newcommand\TikzSvgDisplay[3]{\ifvmode\IgnorePar\fi\EndP\tikzsvg@html{#1}#2\tikzsvg@html{#3}\par}
\newcommand\tikzsvg@label[1]{\if\relax\detokenize{#1}\relax\else\label{#1}\fi}
% An equation number, with label #1 (possibly empty)
\newcommand\TikzSvgEq[1]{\refstepcounter{equation}\tikzsvg@label{#1}%
  \tikzsvg@html{number:before}\theequation\tikzsvg@html{number:after}}
% A \tag{#1} (with label #2) and a \tag*{#1}. A tag does not step the equation counter.
\newcommand\tikzsvg@tag[3]{\begingroup\def\theequation{#2}\refstepcounter{equation}\tikzsvg@label{#3}\endgroup
  \addtocounter{equation}{-1}\tikzsvg@html{number#1:before}#2\tikzsvg@html{number#1:after}}
\newcommand\TikzSvgTag{\tikzsvg@tag{}}
\newcommand\TikzSvgTagStar{\tikzsvg@tag{*}}
\InputIfFileExists{FRAGMENTS_FILE}{}{\PackageError{tikz2html}{FRAGMENTS_FILE not found}{}}
\makeatother
"""

DEFAULT_TEX4HT_CONFIG = "\\Preamble{xhtml}\n\\begin{document}\n\\EndPreamble\n"


def tex4ht_config(config: Config) -> str:
    """The contents of the generated tex4ht configuration file: the user's configuration, extended with the
    placeholder definitions, the additional css and the additional html/javascript."""
    if config.make4ht_config:
        user_cfg = read_config_file(config, config.make4ht_config, "make4ht_config")
    else:
        user_cfg = DEFAULT_TEX4HT_CONFIG
    m = re.search(r"^[^%\n]*\\begin\s*\{document\}", user_cfg, re.M)
    if not m:
        raise Tikz2HtmlError(f"The tex4ht configuration {config.make4ht_config} has no \\begin{{document}}. "
                             f"It should look like \\Preamble{{xhtml}} ... \\begin{{document}} ... \\EndPreamble")
    extra = [TEX4HT_DEFINITIONS.replace("FRAGMENTS_FILE", fragments_file_name(config))]
    for css in config.additional_css:
        extra.append(f"\\Configure{{AddCss}}{{{os.path.basename(css)}}}")
    if config.extra_js:  # Deferred scripts run once the page is parsed, like scripts at the end of the body
        scripts = "".join(f'<script type="text/javascript" src="{os.path.basename(js)}" defer="defer"></script>'
                          for js in config.extra_js)
        extra.append("\\Configure{@HEAD}{\\HCode{" + hcode_escape(scripts) + "\\Hnewline}}")
    if config.additional_html:
        html = read_config_file(config, config.additional_html, "additional_html").strip()
        extra.append("\\Configure{@/BODY}{\\ifvmode\\IgnorePar\\fi\\EndP\\HCode{" + hcode_escape(html) + "}}")
    extra.append("%%%%%%%%%% End of the part added by tikz2html %%%%%%%%%%\n")
    pos = m.start() + m.group(0).index("\\begin")
    return user_cfg[:pos] + "\n".join(extra) + user_cfg[pos:]


def read_config_file(config: Config, name: str, key: str) -> str:
    path = config.path(name)
    if not os.path.isfile(path):
        raise Tikz2HtmlError(f"The file {path} does not exist (from '{key}' in the configuration)")
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        return f.read()


def make4ht_build_file(config: Config) -> str:
    """A make4ht build file running latex, bibtex, and latex again (in non-draft mode)."""
    lines = ["-- Generated by tikz2html", 'if mode == "draft" then', "  Make:htlatex {}", "else", "  Make:htlatex {}"]
    if config.bibtex:
        lines += [f'  Make:add("tikz2html_bibtex", "{config.bibtex} ${{input}}")', "  Make:tikz2html_bibtex {}"]
    lines += ["  Make:htlatex {}"] * config.latex_passes
    lines += ["end", ""]
    return "\n".join(lines)


def tex_env(config: Config) -> dict:
    """Environment for running TeX: the project root is added to the search paths, so that the packages,
    styles and bibliography do not have to be copied into the html folder."""
    env = dict(os.environ)
    for var in ("TEXINPUTS", "BIBINPUTS", "BSTINPUTS"):
        current = env.get(var, "")
        env[var] = os.pathsep.join([".", config.root, current]) if current else os.pathsep.join([".", config.root, ""])
    return env


def run_make4ht(config: Config, draft=False, log=print):
    """Runs make4ht on the main file in the html folder. Returns the exit code."""
    html_dir = config.html_dir
    cfg_name = config.main_name + "-tikz2html.cfg"
    with open(os.path.join(html_dir, cfg_name), "w", encoding="utf-8") as f:
        f.write(tex4ht_config(config))
    build_name = config.main_name + "-tikz2html.mk4"
    with open(os.path.join(html_dir, build_name), "w", encoding="utf-8") as f:
        f.write(make4ht_build_file(config))
    fmt = config.make4ht_format + "".join("+" + e for e in config.make4ht_extensions)
    cmd = [config.make4ht_cmd, "-c", cfg_name, "-e", build_name, "-f", fmt] + list(config.make4ht_flags)
    if draft:
        cmd += ["-m", "draft"]
    cmd += [config.main_name + ".tex", config.make4ht_options]
    log("Running " + " ".join(cmd))
    log_file = os.path.join(html_dir, config.main_name + "-make4ht.log")
    try:
        with open(log_file, "w", encoding="utf-8", errors="replace") as f:
            result = subprocess.run(cmd, cwd=html_dir, env=tex_env(config), stdin=subprocess.DEVNULL, stdout=f,
                                    stderr=subprocess.STDOUT, timeout=config.make4ht_timeout or None)
    except subprocess.TimeoutExpired:
        raise Tikz2HtmlError(
            f"make4ht did not finish within {config.make4ht_timeout} seconds (make4ht_timeout in the configuration). "
            f"TeX may be in an endless loop; find the cause by converting a part of the document with "
            f"--files ... --draft, and look at the end of {config.main_name}.log in {html_dir}")
    except OSError as e:
        raise Tikz2HtmlError(f"Could not run make4ht ({config.make4ht_cmd}): {e}")
    return result.returncode


def bibtex_problems(config: Config):
    """Errors and warnings in the bibtex log of the html run."""
    blg = os.path.join(config.html_dir, config.main_name + ".blg")
    if not config.bibtex or not os.path.exists(blg):
        return []
    with open(blg, "r", encoding="latin-1") as f:
        text = f.read()
    problems = re.findall(r"^(?:I couldn't open.*|I found no .*|Warning--.*|.*---line \d+ of file .*)$", text, re.M)
    return [f"bibtex: {p.strip()}" for p in problems[:10]]


def latex_errors(log_file):
    """The error messages (lines starting with '!') in a LaTeX log file, with their line numbers."""
    if not os.path.exists(log_file):
        return []
    with open(log_file, "r", encoding="latin-1") as f:
        log = f.read()
    return re.findall(r"^! .*(?:\n(?!!).*){0,2}", log, re.M)


def copy_files(config: Config):
    """Copies the files the html needs (css, javascript, images) into the html folder."""
    for fname in list(config.files_to_copy) + list(config.additional_css) + list(config.extra_js):
        src = config.path(fname)
        dst = os.path.join(config.html_dir, os.path.basename(fname))
        if not os.path.exists(src):
            key = ("additional_css" if fname in config.additional_css else
                   "extra_js" if fname in config.extra_js else "files_to_copy")
            raise Tikz2HtmlError(f"The file {src} does not exist (from '{key}' in the configuration)")
        if not os.path.exists(dst) or os.path.getmtime(src) > os.path.getmtime(dst) or os.path.getsize(src) != os.path.getsize(dst):
            shutil.copy2(src, dst)


def html_files(config: Config):
    """The html files generated by make4ht (read from the .lg file, falling back to all html files)."""
    lg = os.path.join(config.html_dir, config.main_name + ".lg")
    files = []
    if os.path.exists(lg):
        with open(lg, "r", encoding="utf-8", errors="replace") as f:
            files = re.findall(r"^File: (.*\.html)\s*$", f.read(), re.M)
    if not files and os.path.isdir(config.html_dir):
        files = [f for f in os.listdir(config.html_dir) if f.endswith(".html")]
    return sorted(set(files))
